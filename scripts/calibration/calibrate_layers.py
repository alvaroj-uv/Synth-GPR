#!/usr/bin/env python3
"""
Bayesian layer calibration: optuna TPE on fast 2D gprMax simulations.

Each trial generates a minimal 2D .in file (250×1×630 cells, ~5 s on CPU),
runs gprMax, then computes Pearson r between the synthetic Ey coda and a real
DZT trace in the 4–20 ns window after the direct wave.

Layer geometry is fixed (from scene_3d_5layer_split_natgnd_e14):
  deep_natgnd  0.00–0.15 m   [subgrade]
  natgnd_upper 0.15–0.30 m
  bedrock      0.30–0.40 m
  formation    0.40–0.50 m
  subballast   0.50–0.65 m
  ballast_void 0.65–1.00 m   (eps=4.5, no rocks — flat layer proxy)
  standoff     1.00–1.05 m   (air)
  source/rx    z=1.052 m     (y-polarised Hertzian dipole, Ricker 400 MHz)

Free parameters (8):
  subballast_eps, formation_eps, bedrock_eps, natgnd_upper_eps, deep_natgnd_eps
  formation_sigma, natgnd_upper_sigma, deep_natgnd_sigma

Usage:
    python scripts/calibration/calibrate_layers.py \\
        --dzt "D:/Codigo/Data/...DZT" --trace 77000 \\
        --trials 100 --study calib_v1
"""
