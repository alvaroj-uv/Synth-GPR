#!/usr/bin/env python3
"""Train a RandomForestRegressor to predict rock COUNT from waveform features
alone, on the target_fill x seed sweep generated by generate_dataset.py.

N=100 follow-up to ../rock_count_rf/ (N=36, which found NO robust signal:
R^2 <= 0 for every model tried). Same method, just more samples.

Ground truth: count of '#cylinder' lines in each sample's .in (exact, since
rock_shape="circle" makes each rock exactly one #cylinder command).
Features: the project's canonical extract_features() (src/feature_extraction.py),
same extractor used for the real waveform-only fouling classification work.

Uses 5-fold cross-validation, reports mean +/- std across folds.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT))

from src.data_loader import read_ascan  # noqa: E402
from src.feature_extraction import extract_features  # noqa: E402


def main():
    in_files = sorted(HERE.glob("sample_*.in"))
    out_files = sorted(HERE.glob("sample_*.out"))
    print(f"Found {len(in_files)} .in files, {len(out_files)} .out files")

    signals = {}
    n_rocks = {}
    dt = None
    t_ns = None

    for out_path in out_files:
        tag = out_path.stem  # e.g. sample_f060_s01
        in_path = out_path.with_suffix(".in")
        if not in_path.exists():
            continue
        n_rocks[tag] = in_path.read_text().count("#cylinder")

        data = read_ascan(out_path, "Ez")
        signals[tag] = data["signal"]
        if dt is None:
            dt = data["dt"]
            t_ns = data["t_ns"]

    tags = sorted(signals.keys())
    print(f"Loaded {len(tags)} traces, dt={dt*1e9:.4f} ns, n_samples={len(t_ns)}")

    df = pd.DataFrame({"Time": t_ns})
    for tag in tags:
        df[tag] = signals[tag]

    print("Extracting waveform features (this project's canonical extract_features)...")
    feat_df = extract_features(df, dt=dt, center_freq_hz=420e6)
    feat_df = feat_df.set_index("Signal").loc[tags]

    drop_cols = [c for c in feat_df.columns if c.startswith("meta_")]
    X = feat_df.drop(columns=drop_cols).select_dtypes(include=[np.number])
    y = np.array([n_rocks[t] for t in tags])

    print(f"\nFeature matrix: {X.shape[0]} samples x {X.shape[1]} features")
    print(f"Target (rock count): min={y.min()} max={y.max()} mean={y.mean():.1f} std={y.std():.1f}")

    from sklearn.ensemble import RandomForestRegressor
    from sklearn.linear_model import LinearRegression
    from sklearn.model_selection import KFold, cross_val_score

    rf = RandomForestRegressor(n_estimators=300, random_state=0, n_jobs=-1)
    kf = KFold(n_splits=5, shuffle=True, random_state=0)

    r2_scores = cross_val_score(rf, X, y, cv=kf, scoring="r2")
    mae_scores = -cross_val_score(rf, X, y, cv=kf, scoring="neg_mean_absolute_error")

    print("\n" + "=" * 60)
    print(f"5-FOLD CROSS-VALIDATION RESULTS (N={len(tags)})")
    print("=" * 60)
    print(f"R^2:  {r2_scores.mean():.3f} +/- {r2_scores.std():.3f}  (per-fold: {np.round(r2_scores, 3)})")
    print(f"MAE:  {mae_scores.mean():.1f} +/- {mae_scores.std():.1f} rocks  "
          f"(per-fold: {np.round(mae_scores, 1)})")
    print(f"Target range: {y.min()}-{y.max()} rocks (span={y.max()-y.min()}), "
          f"so MAE/span = {mae_scores.mean()/(y.max()-y.min())*100:.1f}%")

    # Same simple checks as the N=36 run, for direct comparison
    print("\nSimple correlation checks (no CV):")
    from scipy.stats import pearsonr
    mask_cols = [c for c in ["coda_peak_max", "peak_max"] if c in X.columns]
    for col in mask_cols:
        r, p = pearsonr(y, X[col])
        print(f"  n_rocks vs {col}: pearson r={r:.3f} p={p:.4f}")

    lr = LinearRegression()
    if mask_cols:
        r2_lr = cross_val_score(lr, X[[mask_cols[0]]], y, cv=kf, scoring="r2")
        print(f"  LinearRegression({mask_cols[0]} only), CV R^2 = {r2_lr.mean():.3f} +/- {r2_lr.std():.3f}")

    # Fit on full data for feature importances (descriptive only, not held-out)
    rf.fit(X, y)
    importances = pd.Series(rf.feature_importances_, index=X.columns).sort_values(ascending=False)
    print("\nTop 15 features by importance (fit on full data, NOT held-out):")
    print(importances.head(15).to_string())

    # Save results
    out_csv = HERE / "rf_feature_importances.csv"
    importances.to_csv(out_csv, header=["importance"])
    print(f"\nSaved {out_csv}")

    results_txt = HERE / "rf_results.txt"
    with open(results_txt, "w") as f:
        f.write(f"N samples: {len(tags)}\n")
        f.write(f"N features: {X.shape[1]}\n")
        f.write(f"Target range: {y.min()}-{y.max()} rocks\n")
        f.write(f"R^2 (5-fold CV): {r2_scores.mean():.3f} +/- {r2_scores.std():.3f}\n")
        f.write(f"Per-fold R^2: {list(np.round(r2_scores, 3))}\n")
        f.write(f"MAE (5-fold CV): {mae_scores.mean():.1f} +/- {mae_scores.std():.1f} rocks\n")
        f.write(f"Per-fold MAE: {list(np.round(mae_scores, 1))}\n")
        f.write("\nTop 15 features:\n")
        f.write(importances.head(15).to_string())
    print(f"Saved {results_txt}")


if __name__ == "__main__":
    main()
